// Every photograph gets a little paragraph beneath it — history, the meaning of
// its Hawaiian name, or an interesting factoid.
const storyById: Record<string, string[]> = {
  ...natureStories,
  ...cultureStories,
  ...islandLifeStories,
};

for (const collection of collections) {
  for (const puzzle of collection.puzzles) {
    const story = storyById[puzzle.id];
    if (!puzzle.story && story) {
      puzzle.story = story;
    }
  }
}

/** Collections shown in the gallery and on the home screen (secret ones excluded). */
export const visibleCollections = collections.filter((c) => !c.hidden);

export const freeCollection = collections[0]!;

export function findPuzzle(puzzleId: string) {
  for (const collection of collections) {
    const puzzle = collection.puzzles.find((p) => p.id === puzzleId);
    if (puzzle) return { puzzle, collection };
  }
  return null;
}

